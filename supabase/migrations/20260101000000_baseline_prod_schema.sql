-- Baseline schema, captured from the live project on 23 Sept 2026.
--
-- Why this file exists: until now no tracked migration created companies,
-- shipments, user_profiles, user_settings, api_keys or the other base tables.
-- They were applied by pasting supabase/schema.sql and the loose
-- supabase/migration_*.sql files into the SQL editor by hand, so a fresh
-- project could not be rebuilt -- `supabase db reset` died on the first
-- migration with: relation "public.shipments" does not exist.
--
-- This file is `supabase/db dump --schema public` against the live project,
-- and therefore represents production as it really is, including the seven
-- companies columns (city, state, pin, state_code, port_of_loading, gstin,
-- address) that no file in git ever created. Note `pin` is integer in
-- production, not text.
--
-- The migrations it supersedes are kept for reference under
-- supabase/archive/. Do not edit this file to change the schema; add a new
-- migration after it instead.
--
-- Two objects live outside the `public` schema and so are NOT in the dump:
--   1. the `on_auth_user_created` trigger on auth.users -- re-added at the
--      foot of this file, recovered from supabase/schema.sql. Without it a
--      new signup gets no company, profile or settings row.
--   2. the event trigger driving public.rls_auto_enable(). Event triggers are
--      cluster-level, not schema-scoped. It is a belt-and-braces net that
--      turns RLS on for any future table; every table below already has RLS
--      enabled explicitly, so a rebuild is correct without it. Supabase
--      installs this on new projects itself -- left alone deliberately.




