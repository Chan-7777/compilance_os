CREATE OR REPLACE FUNCTION "public"."cleanup_rate_limits"() RETURNS "void"
    LANGUAGE "plpgsql"
    AS $$
BEGIN
  DELETE FROM public.rate_limits WHERE window_date < CURRENT_DATE - INTERVAL '7 days';
END;
$$;


